'use strict';

/**
 * HTML escaping for interpolated strings (list items, modals, history).
 */

function escapeHtml(str) {
  if (!str) return '';
  return String(str).replace(/[&<>"']/g, (m) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  }[m]));
}

module.exports = { escapeHtml };
